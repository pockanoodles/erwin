#!/usr/bin/env node
/**
 * Copies src/lib/brand.ts into the Electron shell as desktop/src/brand.ts.
 *
 * The shell compiles on its own (rootDir is desktop/src), so it cannot import
 * the app's file directly. Copying keeps one source of truth. The copy is
 * ignored by git and refreshed by the shell's `prebuild` and `pretypecheck`.
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const source = path.join(root, "src", "lib", "brand.ts");
const target = path.join(root, "desktop", "src", "brand.ts");

const text = fs.readFileSync(source, "utf8");
if (/^\s*import\s/m.test(text)) {
  throw new Error("src/lib/brand.ts must not import anything: the desktop shell compiles it alone");
}
fs.writeFileSync(
  target,
  `// Generated by scripts/desktop/sync-brand.mjs from src/lib/brand.ts. Do not edit.\n${text}`
);
